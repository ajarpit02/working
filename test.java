public class FunctionsOverview {

    // Java function (method)
    static int add(int a, int b) {
        return a + b;
    }

    public static void main(String[] args) {
        int result = add(5, 3);
        System.out.println("Result: " + result);

        /*
         JavaScript function example:

         function add(a, b) {
             return a + b;
         }
        */
    }
}
